/* Goal shapes the prescription rather than the exercise selection. */
const GOAL_RX = {
  muscle: { repRange: '8–10', restMul: 1.35, setBonusCompound: 1, setBase: 3 },
  fat_loss: { repRange: '14–16', restMul: 0.6, setBonusCompound: 0, setBase: 3 },
  tone: { repRange: '12–15', restMul: 0.85, setBonusCompound: 0, setBase: 3 },
  general: { repRange: '10–12', restMul: 1.0, setBonusCompound: 0, setBase: 3 },
}

export function setsRepsFor(exercise, goal) {
  const rx = GOAL_RX[goal] ?? GOAL_RX.general
  const sets = rx.setBase + (exercise.compound ? rx.setBonusCompound : 0)
  const restSec = Math.round((exercise.restSec * rx.restMul) / 5) * 5

  // Timed work (planks, intervals, holds) is prescribed in seconds, not reps.
  const reps = exercise.loadType === 'timed' ? `${exercise.estTimePerSet}s` : rx.repRange

  return { sets, reps, restSec }
}

/** Seconds one full exercise occupies, rest included but trailing rest dropped. */
export function timeCostOf(exercise, goal) {
  const { sets, restSec } = setsRepsFor(exercise, goal)
  const SETUP = 40 // walking over, adjusting the bench, loading plates
  return SETUP + sets * exercise.estTimePerSet + (sets - 1) * restSec
}

